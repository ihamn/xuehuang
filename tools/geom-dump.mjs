import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { SIM_ROOT as SIM } from './sim-root.mjs';   // 模拟器位置：一处解析（云电脑/本机通用）
const W = 1880.733, H = 900;
const { createRuntime } = await import(pathToFileURL(path.join(SIM, 'client/lua-runtime/src/index.js')).href);
const rt = createRuntime({ canvasWidth: W, canvasHeight: H });
const root = rt.addRoot({ name: 'Canvas', kind: 'container' });
root.SetActive(true);
for (const [i, k] of [[1, 'image'], [2, 'textbox'], [3, 'cursor'], [4, 'container']]) rt.registerTemplate(i, { kind: k });
rt.mountScript({ path: 'main', source: fs.readFileSync('dist/xuehuang.lua', 'utf8'), control: root, params: {} });
for (let f = 0; f < 5; f++) rt.step(1 / 30);
rt.injectKey('KeyboardJumpKeyDown');
for (let f = 0; f < 200; f++) rt.step(1 / 30);
const find = (c, n) => { if (c.name === n) return c; for (const k of (c.children || [])) { const r = find(k, n); if (r) return r; } return null; };
const row = (n, label) => {
  const c = find(root, n);
  if (!c) return console.log('  ' + n + ' 不存在');
  const l = Math.round(W / 2 + c.anchoredPositionX - c.sizeDeltaX / 2);
  const r = Math.round(W / 2 + c.anchoredPositionX + c.sizeDeltaX / 2);
  const t = Math.round(H / 2 - c.anchoredPositionY - c.sizeDeltaY / 2);
  const b = Math.round(H / 2 - c.anchoredPositionY + c.sizeDeltaY / 2);
  console.log(`  ${(label || n).padEnd(12)} x[${String(l).padStart(5)},${String(r).padStart(5)}] y[${String(t).padStart(4)},${String(b).padStart(4)}]  "${String(c.text || '').slice(0, 14)}"`);
};
console.log('  ── 左列 ──');
for (const n of ['OrderPanel', 'Od_1', 'OdW_1', 'OdTt_1', 'OdS_1', 'OdB_1', 'OdPc_1', 'DataBox', 'DataHead', 'DataL1', 'DataV1', 'DataL9', 'DataV9']) row(n);
console.log('  ── 中列 ──');
for (const n of ['St_shake_box', 'StN_shake', 'StS_shake', 'Pk_box']) row(n);
console.log('  ── 右列 ──');
for (const n of ['BookBox', 'BookHead', 'BookN1', 'KeysBox', 'KeysHead']) row(n);
console.log('  ── HUD ──');
for (const n of ['HudBar', 'HudTip']) row(n);
